/**
 * Merge API rows with the seed set. If a firm exists in the API by
 * normalised name key, the API row wins (it has real sourced findings).
 * Any seed firm not yet in the API is appended so the tracker never looks empty.
 */
export function mergeWithSeed(apiRows = []) {
  const seenKeys = new Set(
    apiRows
      .map(r => (r.firm_name || "").toLowerCase().trim().replace(/\s+/g, " "))
      .filter(Boolean)
  );
  const extras = SEED_FIRMS.filter(
    s => !seenKeys.has(s.firm_name_key)
  );
  return [...apiRows, ...extras];
}
